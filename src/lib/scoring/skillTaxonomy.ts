// Flattened list of all canonical skills
export const ALL_SKILLS: string[] = Object.values(SKILL_TAXONOMY).flat();

// Lookup map for fast category lookup by canonical skill name (case-insensitive)
export const SKILL_TO_CATEGORY: Map<string, SkillCategory> = new Map();

for (const [category, skills] of Object.entries(SKILL_TAXONOMY) as [SkillCategory, string[]][]) {
  for (const skill of skills) {
    SKILL_TO_CATEGORY.set(skill.toLowerCase(), category);
  }
}

export function getSkillCategory(skill: string): SkillCategory {
  const normalized = skill.trim().toLowerCase();
  return SKILL_TO_CATEGORY.get(normalized) ?? "Testing & Tooling";
}

export function getAllSkillsCount(): number {
  return ALL_SKILLS.length;
}
